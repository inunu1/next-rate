/**
 * ============================================================================
 * 【ファイル名】
 * user.ts
 *
 * 【機能概要】
 * 団体ユーザー（User）に関する型定義を集約する。
 *
 * 【役割】
 * - User API（/api/private/user）の Request / Response 型を提供
 * - フロント・API・サービス層で共通利用する型を一元管理
 *
 * 【設計方針】
 * - API 層に型を埋め込まず、本ファイルに集約することで保守性を向上
 * - SIer 風に「業務仕様が読み取れる型コメント」を付与
 * ============================================================================
 */

/* ============================================================================
 * ロール種別（User.role）
 *  - owner : サービス運営者（複数団体を管理）
 *  - admin : 団体管理者（自団体のみ操作可能）
 * ============================================================================
 */
export type UserRole = "owner" | "admin";

/* ============================================================================
 * POST /api/private/user のリクエストボディ
 *
 * 【業務仕様】
 * - owner が新規団体ユーザーを登録する際に使用
 * - email はユニーク制約
 * - password は API 内で bcrypt ハッシュ化される
 * ============================================================================
 */
export type PostUserBody = {
  /** 団体名（表示名） */
  name: string;

  /** ログイン用メールアドレス（ユニーク） */
  email: string;

  /** 平文パスワード（API 内でハッシュ化） */
  password: string;

  /** ロール（owner / admin） */
  role: UserRole;
};

/* ============================================================================
 * DELETE /api/private/user のリクエストボディ
 *
 * 【業務仕様】
 * - owner が団体ユーザーを物理削除する際に使用
 * ============================================================================
 */
export type DeleteUserBody = {
  /** 削除対象ユーザーの ID */
  id: string;
};

/* ============================================================================
 * User 一覧取得（GET /api/private/user）のレスポンス型
 *
 * 【備考】
 * - Prisma の User モデルをそのまま返却するため、
 *   必要に応じてフロント側で Pick して利用する想定
 * ============================================================================
 */
export type UserListResponse = {
  id: string;
  name: string;
  email: string;
  role: UserRole;
  createdAt: Date;
  updatedAt: Date;
};
